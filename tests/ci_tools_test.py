"""CI generated-code validation and artifact contents; synthetic files only, no disc needed."""
import argparse
import importlib.util
import io
from pathlib import Path
import subprocess
import tarfile
import tempfile
import unittest
from unittest.mock import patch
import zipfile

ROOT = Path(__file__).resolve().parent.parent


def module(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / (name + ".py"))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    return m


bundle = module("ci_recomp_bundle")
packager = module("package_build")


class BundleTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="ujl-ci-test-")
        self.root = Path(self.temp.name)
        self.generated = self.root / "gen"; self.generated.mkdir()
        (self.generated / "recomp_dispatch.c").write_text("/* generated by tools/recomp/gen.py */\n")
        (self.generated / "recomp_files.cmake").write_text("set(RECOMP_SOURCES)\n")
        (self.generated / "disc.bin").write_bytes(b"must never be included")
        inputs = self.root / "tools/recomp"; inputs.mkdir(parents=True)
        for name in bundle.INPUTS:
            (inputs / name).write_text("synthetic generator input\n")
        self.patch = patch.object(bundle, "ROOT", self.root); self.patch.start()
        self.archive = self.root / "code.tar.gz"
        bundle.pack(argparse.Namespace(generated=self.generated, output=self.archive))

    def tearDown(self):
        self.patch.stop(); self.temp.cleanup()

    def unpack(self):
        bundle.unpack(argparse.Namespace(input=self.archive, output=self.root / "unpacked"))

    def test_round_trip_excludes_disc_files(self):
        self.unpack()
        self.assertEqual(sorted(p.name for p in (self.root / "unpacked").iterdir()),
                         ["recomp_dispatch.c", "recomp_files.cmake"])

    def test_modified_source_rejected(self):
        with tarfile.open(self.archive, "r:gz") as tf:
            members = [(m, tf.extractfile(m).read()) for m in tf]
        with tarfile.open(self.archive, "w:gz") as tf:
            for info, data in members:
                if info.name == "recomp_dispatch.c": data += b"changed"; info.size = len(data)
                tf.addfile(info, io.BytesIO(data))
        with self.assertRaisesRegex(ValueError, "manifest"): self.unpack()
        self.assertFalse((self.root / "unpacked").exists())

    def test_stale_generator_rejected(self):
        (self.root / "tools/recomp/gen.py").write_text("changed generator\n")
        with self.assertRaisesRegex(ValueError, "stale"): self.unpack()
        self.assertFalse((self.root / "unpacked").exists())

    def test_archive_path_traversal_rejected(self):
        with tarfile.open(self.archive, "w:gz") as tf:
            info = tarfile.TarInfo("../outside.c"); info.size = 3
            tf.addfile(info, io.BytesIO(b"bad"))
        with self.assertRaisesRegex(ValueError, "Unexpected archive"): self.unpack()
        self.assertFalse((self.root / "outside.c").exists())

    def test_repacking_unchanged_sources_is_deterministic(self):
        before = self.archive.read_bytes()
        bundle.pack(argparse.Namespace(generated=self.generated, output=self.archive))
        self.assertEqual(self.archive.read_bytes(), before)


class PackageTests(unittest.TestCase):
    def test_desktop_artifacts_exclude_user_data_and_keep_permissions(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); build = root / "build"; build.mkdir()
            for name in ["ujl.exe", "ujl", "disc.bin", "ujl.ini", "card.mcd"]:
                (build / name).write_bytes(b"synthetic fixture")
            output = root / "dist"
            windows = packager.package("windows-x64", build, output, "test")
            with zipfile.ZipFile(windows) as z:
                names = z.namelist()
                self.assertTrue(any(n.endswith("/ujl.exe") for n in names))
                self.assertFalse(any(n.endswith((".bin", ".ini", ".mcd")) for n in names))
            for platform in ["linux-x64", "macos-arm64", "macos-x64"]:
                artifact = packager.package(platform, build, output, "test")
                with tarfile.open(artifact) as tf:
                    self.assertEqual(tf.getmember("UltimateUJL-" + platform + "/ujl").mode & 0o777, 0o755)

    def test_ipa_has_payload_and_rejects_disc_files(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp); app = root / "build/UltimateUJL.app"; app.mkdir(parents=True)
            (app / "UltimateUJL").write_bytes(b"synthetic executable")
            (app / "Info.plist").write_text("synthetic plist")
            with patch.object(packager.subprocess, "run", return_value=subprocess.CompletedProcess([], 1)):
                ipa = packager.package("ios-arm64", app.parent, root / "out", "test")
            with zipfile.ZipFile(ipa) as z:
                self.assertIn("Payload/UltimateUJL.app/UltimateUJL", z.namelist())
                self.assertTrue(all(n.startswith("Payload/UltimateUJL.app/") for n in z.namelist()))
            (app / "disc.bin").write_bytes(b"must not ship")
            with self.assertRaisesRegex(ValueError, "must not be packaged"):
                packager.package("ios-arm64", app.parent, root / "out2", "test")


if __name__ == "__main__":
    unittest.main()
