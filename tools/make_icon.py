"""Builds the app icon from assets/icon/lammy_head.png (the user's art): crops to the drawn area, centers it on a
square transparent canvas, and writes assets/icon/ujl.ico (Windows exe icon, several sizes) plus
src/frontend/app_icon.h (64x64 RGBA for SDL_SetWindowIcon on every platform).
usage: python tools/make_icon.py"""
import os
from PIL import Image

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = Image.open(os.path.join(root, "assets/icon/lammy_head.png")).convert("RGBA")
art = src.crop(src.getbbox())
side = max(art.size)
pad = max(2, side // 32)            # a little breathing room
canvas = Image.new("RGBA", (side + 2 * pad, side + 2 * pad), (0, 0, 0, 0))
canvas.paste(art, ((canvas.width - art.width) // 2, (canvas.height - art.height) // 2), art)
big = canvas.resize((256, 256), Image.LANCZOS)
big.save(os.path.join(root, "assets/icon/ujl.ico"), sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
big.save(os.path.join(root, "assets/icon/ujl_256.png"))
small = canvas.resize((64, 64), Image.LANCZOS)
px = small.tobytes()
with open(os.path.join(root, "src/frontend/app_icon.h"), "w") as f:
    f.write("// Generated by tools/make_icon.py from assets/icon/lammy_head.png. 64x64 RGBA.\n#pragma once\n")
    f.write("static const int k_app_icon_w = 64, k_app_icon_h = 64;\nstatic const unsigned char k_app_icon_rgba[] = {\n")
    for i in range(0, len(px), 32):
        f.write("    " + ",".join(str(b) for b in px[i:i + 32]) + ",\n")
    f.write("};\n")
print("icon:", art.size, "->", canvas.size)
