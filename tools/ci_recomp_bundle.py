"""Bundle generated JP C for playable CI builds; no disc data or secrets are needed.

Refresh with `pack` after changing the generator, seeds, symbols or overrides.
CI runs `unpack` and checks the source fingerprint before compiling.
"""
import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parent.parent
INPUTS = ["gen.py", "analyze.py", "mips.py", "seeds_jp.txt", "overrides_jp.txt", "symbols_jp.txt"]
NAME = re.compile(r"(?:recomp_[a-zA-Z0-9_]+\.[ch]|ov_\d+_\d+\.c|recomp_files\.cmake)\Z")


def fingerprint():
    return {n: hashlib.sha256((ROOT / "tools/recomp" / n).read_bytes()).hexdigest() for n in INPUTS}


def pack(args):
    generated = Path(args.generated)
    files = {p.name: p.read_bytes() for p in generated.iterdir() if NAME.fullmatch(p.name)}
    if "recomp_files.cmake" not in files or "recomp_dispatch.c" not in files:
        raise ValueError("Prepare the JP generated code first (tools/prepare.sh)")
    for name, data in files.items():
        if name.endswith(".c") and not data.startswith(b"/* generated by tools/recomp/gen.py"):
            raise ValueError("Unexpected generated source: " + name)
    manifest = {"schema": 1, "inputs": fingerprint(),
                "files": {n: hashlib.sha256(d).hexdigest() for n, d in files.items()}}
    output = Path(args.output); output.parent.mkdir(parents=True, exist_ok=True)
    # Deterministic output: unchanged generated code produces an identical archive.
    with output.open("wb") as out, gzip.GzipFile(filename="", fileobj=out, mode="wb", mtime=0) as gz:
        with tarfile.open(fileobj=gz, mode="w") as tf:
            for name, data in [("manifest.json", json.dumps(manifest, sort_keys=True).encode()), *sorted(files.items())]:
                info = tarfile.TarInfo(name); info.size = len(data); info.mode = 0o644
                tf.addfile(info, io.BytesIO(data))
    print(f"Bundled {len(files)} generated source files into {output} ({output.stat().st_size} bytes).")


def unpack(args):
    files = {}
    with tarfile.open(args.input, "r:gz") as tf:
        total = 0
        for member in tf:
            if not member.isfile() or (member.name != "manifest.json" and not NAME.fullmatch(member.name)):
                raise ValueError("Unexpected archive entry: " + member.name)
            total += member.size
            if total > 128 * 1024 * 1024 or member.name in files:
                raise ValueError("Invalid archive size or duplicate entry")
            files[member.name] = tf.extractfile(member).read()
    manifest = json.loads(files.pop("manifest.json"))
    if manifest.get("schema") != 1 or manifest.get("inputs") != fingerprint():
        raise ValueError("Generated code is stale: regenerate and run ci_recomp_bundle.py pack again")
    actual = {n: hashlib.sha256(d).hexdigest() for n, d in files.items()}
    if actual != manifest.get("files") or "recomp_dispatch.c" not in files or "recomp_files.cmake" not in files:
        raise ValueError("Generated-code manifest does not match archive")
    output = Path(args.output)
    if output.exists() and any(output.iterdir()):
        raise ValueError("Choose an empty output directory: " + str(output))
    output.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (output / name).write_bytes(data)
    print(f"Verified and unpacked {len(files)} generated source files into {output}.")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest="command", required=True)
    cmd = sub.add_parser("pack")
    cmd.add_argument("--generated", default="build/gen_jp")
    cmd.add_argument("--output", default="ci/recomp-jp.tar.gz")
    cmd = sub.add_parser("unpack")
    cmd.add_argument("--input", default="ci/recomp-jp.tar.gz")
    cmd.add_argument("--output", default="build/gen_ci")
    args = p.parse_args()
    try:
        (pack if args.command == "pack" else unpack)(args)
    except (ValueError, OSError, KeyError, tarfile.TarError) as e:
        p.exit(1, str(e) + "\n")


if __name__ == "__main__":
    main()
